DROP TABLE IF EXISTS game_saves;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS towers;
DROP TABLE IF EXISTS enemies;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE game_saves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    save_name VARCHAR(100) NOT NULL,
    player_hp INT NOT NULL DEFAULT 20,
    gold INT NOT NULL DEFAULT 150,
    current_wave INT NOT NULL DEFAULT 1,
    level_id INT NOT NULL DEFAULT 1,
    towers_json CLOB,
    saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_save_user_name UNIQUE (user_id, save_name),
    CONSTRAINT fk_saves_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE towers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    base_cost INT NOT NULL,
    base_damage INT NOT NULL,
    base_range DOUBLE NOT NULL,
    base_fire_rate DOUBLE NOT NULL,
    upgrade_cost INT NOT NULL,
    sell_ratio DOUBLE NOT NULL DEFAULT 0.6,
    description CLOB,
    CONSTRAINT uq_towers_type UNIQUE (type)
);

CREATE TABLE enemies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    base_hp INT NOT NULL,
    base_speed DOUBLE NOT NULL,
    gold_reward INT NOT NULL,
    damage_to_player INT NOT NULL DEFAULT 1,
    armor DOUBLE NOT NULL DEFAULT 0.0,
    description CLOB,
    CONSTRAINT uq_enemies_type UNIQUE (type)
);

